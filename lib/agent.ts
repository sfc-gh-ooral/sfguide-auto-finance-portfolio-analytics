import { agentName, executeQuery } from './snowflake';
import type { ResultTable } from './types';

// Calls AUTO_FINANCE_AGENT through SNOWFLAKE.CORTEX.DATA_AGENT_RUN and pulls out what the UI shows:
// the answer text, the SQL Cortex Analyst ran, and its result set.
export interface AgentReply {
  text: string;
  sql?: string;
  verifiedQueryUsed?: boolean;
  result?: ResultTable;
  tools: string[];
}

type Json = Record<string, unknown>;

export async function runAgent(question: string): Promise<AgentReply> {
  const body = JSON.stringify({ messages: [{ role: 'user', content: [{ type: 'text', text: question }] }] });
  const { rows } = await executeQuery<{ R: string }>(
    `SELECT SNOWFLAKE.CORTEX.DATA_AGENT_RUN('${agentName()}', ?, TRUE) AS R`, [body]);
  const resp = JSON.parse(rows[0]?.R ?? '{}') as { content?: Json[]; error?: unknown; message?: string };
  if (!resp.content) throw new Error(`Cortex Agent returned no content${resp.message ? `: ${resp.message}` : ''}`);
  const reply: AgentReply = { text: '', tools: [] };
  const texts: string[] = [];
  for (const c of resp.content) {
    if (c.type === 'text') texts.push(String(c.text ?? ''));
    if (c.type === 'tool_use') reply.tools.push(String((c.tool_use as Json)?.name ?? ''));
    if (c.type !== 'tool_result') continue;
    for (const part of ((c.tool_result as Json)?.content as Json[]) ?? []) {
      const j = part.json as Json | undefined;
      if (!j) continue;
      if (typeof j.sql === 'string') {
        reply.sql = String(j.sql).replace(/\s*\/\* Generated by Cortex \*\/;?\s*$/, '');
        reply.verifiedQueryUsed = Boolean(j.verified_query_used);
        const rs = j.result_set as { data?: (string | null)[][]; resultSetMetaData?: { rowType?: { name: string }[] } } | undefined;
        if (rs?.data) reply.result = { columns: (rs.resultSetMetaData?.rowType ?? []).map((r) => r.name), rows: rs.data };
      }
    }
  }
  reply.text = texts.join('\n\n').trim();
  if (!reply.text) throw new Error('Cortex Agent returned no answer text.');
  return reply;
}
