  DATEADD(month, FLOOR(MONTH_INDEX / 3) * 3, '2024-11-01'::DATE) AS VINTAGE_QUARTER,
  AMOUNT_FINANCED AS AMOUNT, APR, TERM_MONTHS, FICO_BAND, FICO_BAND_ORDER, NEW_USED, LTV_PCT, MONTH_INDEX,
