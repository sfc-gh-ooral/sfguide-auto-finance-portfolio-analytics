CREATE OR REPLACE SEMANTIC VIEW AUTO_FINANCE_SV
  TABLES (
    applications AS APPLICATIONS PRIMARY KEY (APP_ID)
      WITH SYNONYMS ('credit applications', 'apps', 'deals', 'submissions')
      COMMENT = 'One row per auto loan credit application, with the decision and, if funded, the amount and APR',
    dealers AS DEALERS PRIMARY KEY (DEALER_ID)
      WITH SYNONYMS ('dealerships', 'dealer partners')
      COMMENT = 'Auto dealers that submit applications',
    contracts AS CONTRACTS PRIMARY KEY (CONTRACT_ID)
      WITH SYNONYMS ('loans', 'funded contracts', 'accounts')
      COMMENT = 'One row per funded auto loan, with origination terms and first-payment-default flag',
    payments AS PAYMENTS_MONTHLY PRIMARY KEY (CONTRACT_ID, SNAPSHOT_MONTH)
      WITH SYNONYMS ('delinquency snapshots', 'payment status', 'month-end status')
      COMMENT = 'Month-end delinquency status and balance for each funded contract; no rows after charge-off',
    dealer_monthly AS DEALER_MONTHLY PRIMARY KEY (DEALER_ID, MONTH)
      WITH SYNONYMS ('dealer targets')
      COMMENT = 'Funded units and target units per dealer and month'
  )
  RELATIONSHIPS (
    applications_to_dealers AS applications (DEALER_ID) REFERENCES dealers,
    contracts_to_dealers AS contracts (DEALER_ID) REFERENCES dealers,
    payments_to_contracts AS payments (CONTRACT_ID) REFERENCES contracts,
    targets_to_dealers AS dealer_monthly (DEALER_ID) REFERENCES dealers
  )
  FACTS (
    applications.funded_flag AS IFF(IS_FUNDED, 1, 0),
    applications.approved_flag AS IFF(DECISION = 'APPROVED', 1, 0),
    applications.apr_pct AS APR COMMENT = 'APR percent; NULL unless funded',
    applications.ltv_value AS LTV_PCT,
    applications.minutes_to_decision AS DECISION_MINUTES,
    contracts.fpd_flag AS IFF(IS_FIRST_PAYMENT_DEFAULT, 1, 0),
    contracts.loan_amount AS AMOUNT,
    payments.dpd30_flag AS IFF(IS_DPD30, 1, 0),
    payments.dpd60_flag AS IFF(IS_DPD60, 1, 0),
    payments.open_flag AS IFF(STATUS_CODE < 4, 1, 0),
    payments.open_balance AS IFF(STATUS_CODE < 4, BALANCE, 0),
    payments.charged_off AS CHARGE_OFF_AMOUNT
  )
  DIMENSIONS (
    applications.application_date AS APP_DATE WITH SYNONYMS ('submitted date', 'app date') COMMENT = 'Date the application was submitted',
    applications.application_month AS APP_MONTH WITH SYNONYMS ('month', 'origination month') COMMENT = 'First day of the application month',
    applications.day_of_week AS DAY_OF_WEEK COMMENT = 'Three-letter day name, e.g. Sat',
    applications.is_weekend AS IS_WEEKEND COMMENT = 'TRUE for Saturday and Sunday applications',
    applications.channel AS CHANNEL WITH SYNONYMS ('origination channel', 'source') COMMENT = 'Dealer portal, Partner marketplace, or Direct',
    applications.fico_band AS FICO_BAND WITH SYNONYMS ('credit tier', 'score band', 'FICO') COMMENT = 'FICO score band: <580, 580-619, 620-679, 680-739, 740+',
    applications.new_used AS NEW_USED WITH SYNONYMS ('vehicle condition') COMMENT = 'New or Used vehicle',
    applications.term AS TERM_MONTHS WITH SYNONYMS ('loan term') COMMENT = 'Loan term in months',
    applications.decision AS DECISION COMMENT = 'APPROVED or DECLINED',
    applications.decline_reason AS DECLINE_REASON COMMENT = 'Primary decline reason; NULL when approved',
    applications.ltv_pct AS LTV_PCT WITH SYNONYMS ('loan to value') COMMENT = 'Loan-to-value ratio in percent',
    dealers.dealer_name AS DEALER_NAME WITH SYNONYMS ('dealer', 'dealership') COMMENT = 'Dealer name',
    dealers.region AS REGION COMMENT = 'Southeast, Southwest, Midwest, Northeast, or West',
    dealers.state AS STATE COMMENT = 'Two-letter state code',
    dealers.dealer_type AS DEALER_TYPE COMMENT = 'Franchise or Independent',
    dealers.relationship_manager AS RELATIONSHIP_MANAGER WITH SYNONYMS ('RM', 'dealer rep') COMMENT = 'Dealer relationship manager',
    contracts.funded_month AS FUNDED_MONTH WITH SYNONYMS ('booked month', 'vintage month') COMMENT = 'First day of the month the loan funded',
    contracts.vintage_quarter AS VINTAGE_QUARTER WITH SYNONYMS ('vintage', 'cohort') COMMENT = 'First day of the funding quarter (Nov-Jan, Feb-Apr, May-Jul, Aug-Oct)',
    contracts.contract_fico_band AS FICO_BAND COMMENT = 'FICO band at origination',
    contracts.contract_new_used AS NEW_USED COMMENT = 'New or Used vehicle',
    contracts.contract_term AS TERM_MONTHS COMMENT = 'Loan term in months',
    payments.snapshot_month AS SNAPSHOT_MONTH WITH SYNONYMS ('as of month', 'month-end') COMMENT = 'Month-end of the status snapshot',
    payments.delinquency_status AS DELINQUENCY_STATUS WITH SYNONYMS ('DPD bucket', 'status') COMMENT = 'Current, 30-59 DPD, 60-89 DPD, 90+ DPD, or Charged off',
    payments.months_on_book AS MONTHS_ON_BOOK WITH SYNONYMS ('MOB', 'loan age') COMMENT = 'Months since funding',
    dealer_monthly.target_month AS MONTH COMMENT = 'Month of the dealer target'
  )
  METRICS (
    applications.total_applications AS COUNT(APP_ID)
      WITH SYNONYMS ('application volume') COMMENT = 'Number of credit applications. Owner: Dealer Sales',
    applications.approved_applications AS SUM(applications.approved_flag)
      WITH SYNONYMS ('approvals') COMMENT = 'Number of approved applications. Owner: Credit Risk',
    applications.approval_rate AS SUM(applications.approved_flag) / NULLIF(COUNT(APP_ID), 0)
      COMMENT = 'Approved applications divided by all applications (0 to 1). Owner: Credit Risk',
    applications.decline_rate AS 1 - SUM(applications.approved_flag) / NULLIF(COUNT(APP_ID), 0)
      COMMENT = 'Declined applications divided by all applications (0 to 1). Owner: Credit Risk',
    applications.funded_contracts AS SUM(applications.funded_flag)
      WITH SYNONYMS ('funded units', 'bookings') COMMENT = 'Number of applications that funded. Owner: Dealer Sales',
    applications.look_to_book_rate AS SUM(applications.funded_flag) / NULLIF(SUM(applications.approved_flag), 0)
      WITH SYNONYMS ('look to book', 'pull-through', 'booking rate') COMMENT = 'Funded contracts divided by approved applications (0 to 1). Owner: Dealer Sales',
    applications.funded_amount AS SUM(AMOUNT_FINANCED)
      WITH SYNONYMS ('funded volume', 'originations volume') COMMENT = 'Total amount financed on funded contracts, USD. Owner: Finance',
    applications.avg_apr AS AVG(applications.apr_pct) COMMENT = 'Average APR on funded contracts, percent. Owner: Finance',
    applications.avg_ltv AS AVG(applications.ltv_value) COMMENT = 'Average loan-to-value ratio on applications, percent. Owner: Credit Risk',
    applications.avg_decision_minutes AS AVG(applications.minutes_to_decision)
      WITH SYNONYMS ('time to decision') COMMENT = 'Average minutes from submission to decision. Owner: Operations',
    contracts.contract_count AS COUNT(CONTRACT_ID) COMMENT = 'Number of funded contracts. Owner: Finance',
    contracts.first_payment_default_rate AS SUM(contracts.fpd_flag) / NULLIF(COUNT(CONTRACT_ID), 0)
      WITH SYNONYMS ('FPD rate', 'first payment default') COMMENT = 'Share of funded contracts whose first payment was 30+ DPD (0 to 1); use contracts funded by Sep 2026. Owner: Credit Risk',
    payments.dpd30_rate AS SUM(payments.dpd30_flag) / NULLIF(SUM(payments.open_flag), 0)
      WITH SYNONYMS ('30+ DPD rate', 'delinquency rate') COMMENT = 'Share of open contracts 30 or more days past due at month-end (0 to 1). Group by snapshot_month. Owner: Credit Risk',
    payments.dpd60_rate AS SUM(payments.dpd60_flag) / NULLIF(SUM(payments.open_flag), 0)
      WITH SYNONYMS ('60+ DPD rate') COMMENT = 'Share of open contracts 60 or more days past due at month-end (0 to 1). Owner: Credit Risk',
    payments.open_balance_amount AS SUM(payments.open_balance)
      WITH SYNONYMS ('receivables', 'outstanding balance') COMMENT = 'Outstanding balance of open contracts, USD. Only meaningful for a single snapshot_month. Owner: Finance',
    payments.total_charge_offs AS SUM(payments.charged_off)
      WITH SYNONYMS ('charge-offs', 'losses', 'write-offs') COMMENT = 'Balance charged off, USD (no recoveries modeled). Owner: Finance',
    dealer_monthly.target_attainment AS SUM(FUNDED_UNITS) / NULLIF(SUM(TARGET_FUNDED_UNITS), 0)
      COMMENT = 'Funded units divided by target units (1 = on target). Owner: Dealer Sales'
  )
  COMMENT = 'Governed semantic layer for synthetic auto finance originations, dealers, delinquency, and charge-offs'
  AI_SQL_GENERATION 'Rates are fractions between 0 and 1; show them as percentages with one decimal. Months run from 2024-11 to 2026-10. "Last quarter" means 2026-08-01 through 2026-10-31. "Last month" and "latest" mean October 2026. Delinquency and balance metrics must be grouped or filtered by snapshot_month.'
  AI_VERIFIED_QUERIES (
    vq_dpd30_by_band_latest AS (
      QUESTION 'What is the 30+ DPD rate by FICO band last month?'
      ONBOARDING_QUESTION TRUE
      SQL 'SELECT payment_fico_band, SUM(dpd30_flag) / NULLIF(SUM(open_flag), 0) AS dpd30_rate FROM __payments WHERE snapshot_month = ''2026-10-01'' GROUP BY payment_fico_band ORDER BY payment_fico_band'
    ),
    vq_dpd30_subprime_trend AS (
      QUESTION 'Show the 30+ DPD rate by month for the 580-619 FICO band'
      ONBOARDING_QUESTION TRUE
      SQL 'SELECT p.snapshot_month, SUM(p.dpd30_flag) / NULLIF(SUM(p.open_flag), 0) AS dpd30_rate FROM __payments p JOIN __contracts c ON p.contract_id = c.contract_id WHERE c.contract_fico_band = ''580-619'' GROUP BY p.snapshot_month ORDER BY p.snapshot_month'
    ),
    vq_chargeoffs_by_vintage AS (
      QUESTION 'What are total charge-offs by vintage quarter?'
      ONBOARDING_QUESTION TRUE
      SQL 'SELECT c.vintage_quarter, SUM(p.charged_off) AS total_charge_offs FROM __payments p JOIN __contracts c ON p.contract_id = c.contract_id GROUP BY c.vintage_quarter ORDER BY c.vintage_quarter'
    ),
    vq_fpd_by_dealer AS (
      QUESTION 'Which dealers have the highest first-payment default rate in 2026?'
      ONBOARDING_QUESTION TRUE
      SQL 'SELECT d.dealer_name, COUNT(*) AS contracts, SUM(c.fpd_flag) / COUNT(*) AS first_payment_default_rate FROM __contracts c JOIN __dealers d ON c.dealer_id = d.dealer_id WHERE c.funded_month BETWEEN ''2026-01-01'' AND ''2026-09-01'' GROUP BY d.dealer_name HAVING COUNT(*) >= 100 ORDER BY first_payment_default_rate DESC LIMIT 10'
    ),
    vq_sunbelt_decline_trend AS (
      QUESTION 'What is the monthly decline rate for Sunbelt Motors Group?'
      SQL 'SELECT a.application_month, 1 - SUM(a.approved_flag) / COUNT(*) AS decline_rate FROM __applications a JOIN __dealers d ON a.dealer_id = d.dealer_id WHERE d.dealer_name = ''Sunbelt Motors Group'' GROUP BY a.application_month ORDER BY a.application_month'
    ),
    vq_look_to_book_weekend AS (
      QUESTION 'How does look-to-book compare on weekends versus weekdays?'
      SQL 'SELECT is_weekend, SUM(funded_flag) / NULLIF(SUM(approved_flag), 0) AS look_to_book_rate FROM __applications GROUP BY is_weekend'
    ),
    vq_funded_by_region_last_quarter AS (
      QUESTION 'What was funded volume by region last quarter?'
      SQL 'SELECT d.region, SUM(a.amount_financed) AS funded_amount FROM __applications a JOIN __dealers d ON a.dealer_id = d.dealer_id WHERE a.application_month BETWEEN ''2026-08-01'' AND ''2026-10-01'' GROUP BY d.region ORDER BY funded_amount DESC'
    )
  );

