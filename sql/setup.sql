-- --------------------------------------------------------------------------
-- 4. APPLICATIONS (1.2M credit applications over 24 months)
-- --------------------------------------------------------------------------
CREATE OR REPLACE TABLE APPLICATIONS COMMENT = 'Synthetic auto loan applications, one row per application' AS
WITH g AS (
  SELECT ROW_NUMBER() OVER (ORDER BY SEQ8()) - 1 AS n
  FROM TABLE(GENERATOR(ROWCOUNT => 1200000))
), h AS (
  SELECT n,
    IFF(MOD(HASH32(n, 3), 10000) < 3500,
        GREATEST(MOD(HASH32(n, 1), 730), MOD(HASH32(n, 2), 730)),
        MOD(HASH32(n, 1), 730)) AS day_idx,
    IFF(MOD(HASH32(n, 4), 10000) < 40, 7,
        IFF(MOD(HASH32(n, 7), 10000) < 5000,
            LEAST(MOD(HASH32(n, 5), 1500), MOD(HASH32(n, 6), 1500)),
            MOD(HASH32(n, 5), 1500)) + 1) AS dealer_id,
    MOD(HASH32(n, 8), 10000)  AS u_channel,
    MOD(HASH32(n, 9), 10000)  AS u_fico,
    MOD(HASH32(n, 10), 10000) AS u_used,
    HASH32(n, 11)             AS h_price,
    HASH32(n, 12)             AS h_ltv,
    MOD(HASH32(n, 13), 10000) AS u_term,
    MOD(HASH32(n, 14), 10000) AS u_approve,
    MOD(HASH32(n, 15), 10000) AS u_ltv_reason,
    MOD(HASH32(n, 16), 10000) AS u_reason,
    HASH32(n, 17)             AS h_minutes,
    MOD(HASH32(n, 18), 10000) AS u_fund,
    HASH32(n, 19)             AS h_apr
  FROM g
), b AS (
  SELECT h.*,
    DATEADD(day, day_idx, '2024-11-01'::DATE) AS app_date,
    DATEDIFF(month, '2024-11-01'::DATE, DATEADD(day, day_idx, '2024-11-01'::DATE)) AS cm,
    CASE WHEN u_fico < 800 THEN 0 WHEN u_fico < 2200 THEN 1 WHEN u_fico < 4800 THEN 2 WHEN u_fico < 7600 THEN 3 ELSE 4 END AS fb,
    u_used < IFF(dealer_id = 7, 7000, 5800) AS is_used,
    CASE WHEN u_term < 1000 THEN 36 WHEN u_term < 2400 THEN 48 WHEN u_term < 5200 THEN 60 WHEN u_term < 8600 THEN 72 ELSE 84 END AS term_months
  FROM h
), c AS (
  SELECT b.*,
    IFF(is_used, 1400000 + MOD(h_price, 2400001), 3200000 + MOD(h_price, 2800001)) AS price_cents,
    IFF(is_used, 80 + MOD(h_ltv, 55), 70 + MOD(h_ltv, 50))
      + IFF(dealer_id = 7 AND is_used AND cm >= 12, (cm - 11) * 3, 0) AS ltv_pct,
    DAYOFWEEKISO(app_date) IN (6, 7) AS is_weekend
  FROM b
), d AS (
  SELECT c.*,
    u_approve < DECODE(fb, 0, 3200, 1, 5200, 2, 7000, 3, 8300, 9100)
      - CASE WHEN ltv_pct > 120 THEN 2600 WHEN ltv_pct > 110 THEN 900 ELSE 0 END AS is_approved
  FROM c
)
SELECT
  n AS APP_ID,
  dealer_id AS DEALER_ID,
  app_date AS APP_DATE,
  DATE_TRUNC(month, app_date) AS APP_MONTH,
  DAYNAME(app_date) AS DAY_OF_WEEK,
  is_weekend AS IS_WEEKEND,
  CASE WHEN u_channel < 7800 THEN 'Dealer portal' WHEN u_channel < 9200 THEN 'Partner marketplace' ELSE 'Direct' END AS CHANNEL,
  DECODE(fb, 0, '<580', 1, '580-619', 2, '620-679', 3, '680-739', '740+') AS FICO_BAND,
  IFF(is_used, 'Used', 'New') AS NEW_USED,
  (price_cents / 100)::NUMBER(12, 2) AS VEHICLE_PRICE,
  ltv_pct AS LTV_PCT,
  term_months AS TERM_MONTHS,
  IFF(is_approved, 'APPROVED', 'DECLINED') AS DECISION,
  CASE WHEN is_approved THEN NULL
       WHEN ltv_pct > 120 AND u_ltv_reason < 7000 THEN 'LTV above policy'
       WHEN u_reason < 3400 THEN 'Credit score'
       WHEN u_reason < 5800 THEN 'Debt-to-income'
       WHEN u_reason < 7400 THEN 'Income verification'
       WHEN u_reason < 8700 THEN 'Vehicle valuation'
       ELSE 'Stipulations not met' END AS DECLINE_REASON,
  IFF(fb = 4, 2 + MOD(h_minutes, 12), 4 + MOD(h_minutes, 46)) AS DECISION_MINUTES,
  is_approved AND u_fund < IFF(is_weekend, 4100, 6300) AS IS_FUNDED,
  IFF(is_approved AND u_fund < IFF(is_weekend, 4100, 6300),
      (FLOOR(price_cents * ltv_pct / 100) / 100)::NUMBER(12, 2), NULL) AS AMOUNT_FINANCED,
  IFF(is_approved AND u_fund < IFF(is_weekend, 4100, 6300),
      ((DECODE(fb, 0, 1890, 1, 1390, 2, 990, 3, 690, 549) + MOD(h_apr, 220)) / 100)::NUMBER(5, 2), NULL) AS APR,
  fb AS FICO_BAND_ORDER,
  cm AS MONTH_INDEX
FROM d;

