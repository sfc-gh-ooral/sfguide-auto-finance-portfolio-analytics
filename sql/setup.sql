CREATE OR REPLACE TEMPORARY TABLE CONTRACT_PATHS AS
WITH r AS (
  SELECT CONTRACT_ID, MONTH_INDEX AS fm, FICO_BAND_ORDER AS fb, TERM_MONTHS AS term, AMOUNT,
    NEW_USED = 'Used' AND TERM_MONTHS = 84 AND MONTH_INDEX BETWEEN 3 AND 5 AS weak,
    DEALER_ID = 23 AND MONTH_INDEX >= 14 AS fpd_dealer,
    DECODE(FICO_BAND_ORDER, 0, 5200, 1, 3200, 2, 1900, 3, 950, 380)
      + IFF(NEW_USED = 'Used' AND TERM_MONTHS = 84 AND MONTH_INDEX BETWEEN 3 AND 5,
            DECODE(FICO_BAND_ORDER, 0, 5200, 1, 3200, 2, 1900, 3, 950, 380) + 600, 0)
      + IFF(DEALER_ID = 23 AND MONTH_INDEX >= 14, 1600, 0)
      + IFF(LTV_PCT > 120, 300, 0) AS p,
    12 + GREATEST(MOD(HASH32(CONTRACT_ID, 28), 12), MOD(HASH32(CONTRACT_ID, 29), 12)) AS cal_start,
    MOD(HASH32(CONTRACT_ID, 30), 10000) AS u_creep,
    MOD(HASH32(CONTRACT_ID, 21), 10000) AS u_dq,
    MOD(HASH32(CONTRACT_ID, 25), 10000) AS u_fpd,
    1 + LEAST(MOD(HASH32(CONTRACT_ID, 22), 18), MOD(HASH32(CONTRACT_ID, 23), 18)) AS start_default,
    MOD(HASH32(CONTRACT_ID, 24), 10000) AS u_out
  FROM CONTRACTS
), s AS (
  SELECT r.*, fb = 1 AND cal_start > fm AND u_creep < 2200 AS creep FROM r
)
SELECT CONTRACT_ID, fm, fb, term, AMOUNT,
  creep OR u_dq < p AS dq,
  IFF(creep, cal_start - fm, IFF(fpd_dealer AND u_fpd < 7000, 1, start_default)) AS start_mob,
  CASE WHEN u_out < IFF(weak, 3000, 5000) THEN 1 WHEN u_out < IFF(weak, 4500, 7000) THEN 2
       WHEN u_out < IFF(weak, 5000, 7500) THEN 3 ELSE 4 END AS outcome
FROM s;

ALTER TABLE CONTRACTS ADD COLUMN IS_FIRST_PAYMENT_DEFAULT BOOLEAN
  COMMENT 'TRUE when the first scheduled payment was 30+ days past due (observed only if funded by Sep 2026)';
UPDATE CONTRACTS c SET IS_FIRST_PAYMENT_DEFAULT = (p.dq AND p.start_mob = 1 AND c.MONTH_INDEX <= 22)
FROM CONTRACT_PATHS p WHERE p.CONTRACT_ID = c.CONTRACT_ID;

-- --------------------------------------------------------------------------
-- 6. PAYMENTS_MONTHLY (month-end status per contract; stops after charge-off)
-- Episode path by outcome: 1 cure after 30, 2 cure after 60, 3 cure after 90+,
-- 4 charge off in the fifth month of the episode.
-- --------------------------------------------------------------------------
CREATE OR REPLACE TABLE PAYMENTS_MONTHLY COMMENT = 'Synthetic month-end payment status per funded contract' AS
WITH k AS (SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS k FROM TABLE(GENERATOR(ROWCOUNT => 23))),
x AS (
  SELECT p.CONTRACT_ID, p.fm, p.term, p.AMOUNT, k.k,
    CASE WHEN NOT p.dq OR k.k < p.start_mob THEN 0
         WHEN p.outcome = 1 THEN IFF(k.k - p.start_mob = 0, 1, 0)
         WHEN p.outcome = 2 THEN CASE k.k - p.start_mob WHEN 0 THEN 1 WHEN 1 THEN 2 ELSE 0 END
         WHEN p.outcome = 3 THEN CASE WHEN k.k - p.start_mob = 0 THEN 1 WHEN k.k - p.start_mob = 1 THEN 2
                                      WHEN k.k - p.start_mob <= 3 THEN 3 ELSE 0 END
         ELSE CASE WHEN k.k - p.start_mob = 0 THEN 1 WHEN k.k - p.start_mob = 1 THEN 2
                   WHEN k.k - p.start_mob <= 3 THEN 3 WHEN k.k - p.start_mob = 4 THEN 4 ELSE -1 END END AS st
  FROM CONTRACT_PATHS p JOIN k ON p.fm + k.k <= 23
)
SELECT
  CONTRACT_ID,
  DATEADD(month, fm + k, '2024-11-01'::DATE) AS SNAPSHOT_MONTH,
  k AS MONTHS_ON_BOOK,
  st AS STATUS_CODE,
  DECODE(st, 0, 'Current', 1, '30-59 DPD', 2, '60-89 DPD', 3, '90+ DPD', 'Charged off') AS DELINQUENCY_STATUS,
  st BETWEEN 1 AND 3 AS IS_DPD30,
  st BETWEEN 2 AND 3 AS IS_DPD60,
  (ROUND(AMOUNT * 100 * (term - k) / term) / 100)::NUMBER(12, 2) AS BALANCE,
  IFF(st = 4, (ROUND(AMOUNT * 100 * (term - k) / term) / 100)::NUMBER(12, 2), 0) AS CHARGE_OFF_AMOUNT
FROM x WHERE st >= 0;

DROP TABLE CONTRACT_PATHS;

-- --------------------------------------------------------------------------
-- 7. DEALER TARGETS and the dealer-month rollup used for attainment
-- --------------------------------------------------------------------------
CREATE OR REPLACE TABLE DEALER_TARGETS COMMENT = 'Synthetic monthly funded-unit targets per dealer' AS
WITH m AS (SELECT DATEADD(month, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, '2024-11-01'::DATE) AS TARGET_MONTH
           FROM TABLE(GENERATOR(ROWCOUNT => 24)))
SELECT d.DEALER_ID, m.TARGET_MONTH, d.TARGET_MONTHLY_UNITS AS TARGET_FUNDED_UNITS
FROM DEALERS d CROSS JOIN m;

CREATE OR REPLACE VIEW DEALER_MONTHLY COMMENT = 'Funded units against target per dealer and month' AS
SELECT t.DEALER_ID, t.TARGET_MONTH AS MONTH, t.TARGET_FUNDED_UNITS,
       COALESCE(a.FUNDED_UNITS, 0) AS FUNDED_UNITS
FROM DEALER_TARGETS t
LEFT JOIN (SELECT DEALER_ID, APP_MONTH, COUNT_IF(IS_FUNDED) AS FUNDED_UNITS
           FROM APPLICATIONS GROUP BY 1, 2) a
  ON a.DEALER_ID = t.DEALER_ID AND a.APP_MONTH = t.TARGET_MONTH;

-- --------------------------------------------------------------------------
-- 8. COLLECTIONS QUEUE: accounts 30-89 DPD at the latest month-end, ranked by
-- a transparent roll-risk score (mirrors rollScore() in the generator).
-- --------------------------------------------------------------------------
CREATE OR REPLACE VIEW COLLECTIONS_QUEUE COMMENT = 'Early-delinquency accounts at Oct 2026 month-end with roll-risk score' AS
SELECT
  c.CONTRACT_ID, c.BORROWER_NAME, c.DEALER_ID, d.DEALER_NAME, p.DELINQUENCY_STATUS, c.FICO_BAND, c.LTV_PCT, c.TERM_MONTHS,
  p.MONTHS_ON_BOOK, c.FUNDED_MONTH, c.AMOUNT, c.APR, p.BALANCE, c.MONTHLY_PAYMENT, c.NEW_USED,
  IFF(p.STATUS_CODE = 2, 45, 25) AS PTS_DELINQUENCY,
  DECODE(c.FICO_BAND_ORDER, 0, 20, 1, 16, 2, 10, 3, 5, 2) AS PTS_CREDIT,
  CASE WHEN c.LTV_PCT > 120 THEN 10 WHEN c.LTV_PCT > 110 THEN 5 ELSE 0 END AS PTS_LTV,
  CASE WHEN c.TERM_MONTHS >= 84 THEN 8 WHEN c.TERM_MONTHS >= 72 THEN 4 ELSE 0 END AS PTS_TERM,
  IFF(p.MONTHS_ON_BOOK <= 6, 8, 0) AS PTS_EARLY,
  PTS_DELINQUENCY + PTS_CREDIT + PTS_LTV + PTS_TERM + PTS_EARLY AS ROLL_RISK_SCORE
FROM PAYMENTS_MONTHLY p
JOIN CONTRACTS c ON c.CONTRACT_ID = p.CONTRACT_ID
JOIN DEALERS d ON d.DEALER_ID = c.DEALER_ID
WHERE p.SNAPSHOT_MONTH = '2026-10-01' AND p.STATUS_CODE IN (1, 2);

